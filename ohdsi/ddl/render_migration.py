"""Render the OHDSI OMOP CDM 5.4 DDL into a dbmate migration (FR-CDM1).

The upstream files are vendored unchanged under upstream/<tag>/. This script splits the
tables across our schemas (vocabulary tables -> vocab, everything else -> cdm), creates
them as the engineer role so default privileges apply, and writes one migration file.

Foreign-key constraints are deliberately not applied: concept references are checked by
the OHDSI Data Quality Dashboard and dbt relationship tests instead.

Usage:
    uv run python ohdsi/ddl/render_migration.py           # write the migration
    uv run python ohdsi/ddl/render_migration.py --check   # fail if it is out of date
"""

import argparse
import re
import sys
from pathlib import Path

CDM_TAG = "v5.4.3"
HERE = Path(__file__).resolve().parent
UPSTREAM = HERE / "upstream" / CDM_TAG
MIGRATION = HERE.parents[1] / "governance" / "migrations" / "20261124000003_create_omop_cdm_5_4.sql"
PARTS = ("ddl", "primary_keys", "indices")

VOCAB_TABLES = frozenset(
    {
        "concept",
        "vocabulary",
        "domain",
        "concept_class",
        "concept_relationship",
        "relationship",
        "concept_synonym",
        "concept_ancestor",
        "source_to_concept_map",
        "drug_strength",
    }
)

PLACEHOLDER = re.compile(r"@cdmDatabaseSchema\.(\w+)")
CREATE_TABLE = re.compile(r"^CREATE TABLE (\w+)\.(\w+)", re.MULTILINE)


def _qualify(match: re.Match[str]) -> str:
    table = match.group(1).lower()
    schema = "vocab" if table in VOCAB_TABLES else "cdm"
    return f"{schema}.{table}"


def _clean(text: str) -> str:
    lines = [line.rstrip() for line in text.splitlines()]
    return "\n".join(lines).strip() + "\n"


def render() -> str:
    body = "\n".join(
        _clean(
            PLACEHOLDER.sub(_qualify, (UPSTREAM / f"OMOPCDM_postgresql_5.4_{part}.sql").read_text())
        )
        for part in PARTS
    )
    if "@" in body:
        raise ValueError("unresolved placeholder left in rendered DDL")
    tables = [f"{schema}.{table}" for schema, table in CREATE_TABLE.findall(body)]
    drops = "\n".join(f"DROP TABLE {table};" for table in reversed(tables))
    return (
        "-- migrate:up\n"
        f"-- Generated by ohdsi/ddl/render_migration.py from OHDSI CommonDataModel {CDM_TAG}.\n"
        "-- Do not edit by hand: change the renderer and re-run it.\n"
        "SET LOCAL ROLE engineer;\n\n"
        f"{body}\n"
        "RESET ROLE;\n\n"
        "-- migrate:down\n"
        "SET LOCAL ROLE engineer;\n"
        f"{drops}\n"
        "RESET ROLE;\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the migration is stale")
    args = parser.parse_args()

    rendered = render()
    if args.check:
        current = MIGRATION.read_text() if MIGRATION.exists() else ""
        if current != rendered:
            print(f"{MIGRATION.name} is out of date; run ohdsi/ddl/render_migration.py")
            return 1
        print(f"{MIGRATION.name} is up to date")
        return 0

    MIGRATION.write_text(rendered)
    print(f"wrote {MIGRATION.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
